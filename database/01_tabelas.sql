-- Tabelas principais do ERP.
-- Testei no Oracle 23ai Free. Precisa ser 12c ou mais novo por causa das colunas identity.

create table clientes (
  id              number generated by default as identity primary key,
  nome            varchar2(120) not null,
  cpf_cnpj        varchar2(14)  not null,
  cidade          varchar2(80),
  uf              char(2),
  telefone        varchar2(20),
  email           varchar2(120),
  limite_credito  number(12,2)  default 0 not null,
  ativo           char(1)       default 'S' not null,
  criado_em       date          default sysdate not null,
  constraint uk_clientes_doc unique (cpf_cnpj),
  constraint ck_clientes_ativo check (ativo in ('S', 'N')),
  constraint ck_clientes_limite check (limite_credito >= 0)
);

create table produtos (
  id              number generated by default as identity primary key,
  codigo          varchar2(20)  not null,
  descricao       varchar2(120) not null,
  unidade         varchar2(3)   default 'UN' not null,
  preco_venda     number(12,2)  not null,
  estoque_atual   number(12,3)  default 0 not null,
  estoque_minimo  number(12,3)  default 0 not null,
  ativo           char(1)       default 'S' not null,
  constraint uk_produtos_codigo unique (codigo),
  constraint ck_produtos_ativo check (ativo in ('S', 'N')),
  constraint ck_produtos_preco check (preco_venda >= 0),
  constraint ck_produtos_estoque check (estoque_atual >= 0)
);

create table pedidos (
  id                number generated by default as identity primary key,
  cliente_id        number        not null,
  data_pedido       date          default sysdate not null,
  status            varchar2(10)  default 'ABERTO' not null,
  valor_total       number(12,2)  default 0 not null,
  observacao        varchar2(400),
  data_faturamento  date,
  constraint fk_pedidos_cliente foreign key (cliente_id) references clientes (id),
  constraint ck_pedidos_status check (status in ('ABERTO', 'FATURADO', 'CANCELADO'))
);

create index ix_pedidos_cliente on pedidos (cliente_id);
create index ix_pedidos_status on pedidos (status, data_pedido);

create table pedido_itens (
  id              number generated by default as identity primary key,
  pedido_id       number        not null,
  produto_id      number        not null,
  quantidade      number(12,3)  not null,
  preco_unitario  number(12,2)  not null,
  desconto_pct    number(5,2)   default 0 not null,
  valor_total     number(12,2)  not null,
  constraint fk_itens_pedido foreign key (pedido_id) references pedidos (id) on delete cascade,
  constraint fk_itens_produto foreign key (produto_id) references produtos (id),
  constraint ck_itens_qtd check (quantidade > 0),
  constraint ck_itens_desconto check (desconto_pct between 0 and 100)
);

create index ix_itens_pedido on pedido_itens (pedido_id);

create table movimentos_estoque (
  id            number generated by default as identity primary key,
  produto_id    number        not null,
  tipo          char(1)       not null,
  quantidade    number(12,3)  not null,
  origem        varchar2(20)  not null,
  documento_id  number,
  data_mov      date          default sysdate not null,
  constraint fk_mov_produto foreign key (produto_id) references produtos (id),
  constraint ck_mov_tipo check (tipo in ('E', 'S')),
  constraint ck_mov_qtd check (quantidade > 0)
);

create index ix_mov_produto on movimentos_estoque (produto_id, data_mov);

create table contas_receber (
  id              number generated by default as identity primary key,
  pedido_id       number        not null,
  cliente_id      number        not null,
  parcela         number(3)     not null,
  vencimento      date          not null,
  valor           number(12,2)  not null,
  valor_pago      number(12,2)  default 0 not null,
  data_pagamento  date,
  status          varchar2(10)  default 'ABERTO' not null,
  constraint fk_cr_pedido foreign key (pedido_id) references pedidos (id),
  constraint fk_cr_cliente foreign key (cliente_id) references clientes (id),
  constraint ck_cr_status check (status in ('ABERTO', 'PAGO', 'CANCELADO'))
);

create index ix_cr_cliente on contas_receber (cliente_id, status);
create index ix_cr_vencimento on contas_receber (status, vencimento);
